/**
 * Returns a translated version of standard strings if available, otherwise fallback to standard text.
 */
let activeLanguage: SupportedLanguage = 'en';

export function setActiveLanguage(lang: string) {
  const normalized = (lang || 'en').toLowerCase();
  if (normalized in TRANSLATIONS) {
    activeLanguage = normalized as SupportedLanguage;
  }
}

export function getActiveLanguage(): SupportedLanguage {
  return activeLanguage;
}

export function getTranslatedLabel(text: string, currentLang?: string): string {
  const langKey = (currentLang || activeLanguage).toLowerCase() as SupportedLanguage;
  if (!TRANSLATIONS[langKey]) return text;
  return TRANSLATIONS[langKey][text] || text;
}

export function t(text: string, currentLang?: string): string {
  return getTranslatedLabel(text, currentLang);
}

